-- 방문이 어느 페이지로 들어왔는지 기록한다.
--
-- 배경: 검색 유입이 주 12~19건에서 3주째 정체인데, 같은 기간 카탈로그는 454개에서 3,802개로
-- 늘었다. 페이지를 3,400개 깔아놓고도 어느 페이지가 검색에서 먹히는지 알 수 없어서,
-- 무엇을 고쳐야 하는지 판단할 근거가 없었다.
--
-- visit_log는 (방문자, 날짜)당 1행이므로 여기 들어가는 path는 그날 그 사람이 처음 연 페이지,
-- 즉 랜딩 페이지가 된다. 세션 내 이동 경로는 기록하지 않는다 — 필요한 건 "어디로 들어오는가"다.
--
-- 쿼리스트링은 저장하지 않는다. 지금 쓰는 파라미터(category 등)에 민감한 값은 없지만,
-- 이 컬럼은 관리자 화면에 그대로 뿌려지므로 나중에 무엇이 붙든 새지 않도록 경로만 남긴다.

alter table visit_log add column if not exists path text;

-- 랜딩 페이지 집계는 "최근 N일 × path"로만 조회하므로 이 조합으로 인덱스를 둔다.
create index if not exists visit_log_date_path_idx on visit_log (visit_date desc, path);

-- 기존 행은 path가 null로 남는다. 되살릴 방법이 없으므로 통계 화면에서는
-- null을 "(before tracking)"으로 따로 표시해, 기록이 없는 것과 루트 방문("/")을 구분한다.

select s.category, count(*) as cnt
from streams s join junk_video_ids j using (video_id)
group by 1 order by 2 desc;

select s.duration_seconds, s.category, s.title
from streams s join junk_video_ids j using (video_id)
order by s.duration_seconds desc
limit 60;

-- 남는 것도 같이 확인 (이쪽이 멀쩡해야 기준이 맞는 것)
select count(*) as 남는_일반영상
from streams
where content_type = 'video' and approval_status = 'approved' and status = 'live'
  and (visibility is null or visibility = 'listed')
  and video_id not in (select video_id from junk_video_ids);

